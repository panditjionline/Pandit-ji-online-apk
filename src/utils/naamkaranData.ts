/**
 * Finds the exact Nakshatra & Pada Naamkaran details for a given Nakshatra index and Pada.
 */
export function getNaamkaranDetails(nakshatraIdx: number, pada: number) {
  const safeIdx = Math.max(0, Math.min(26, nakshatraIdx));
  const nakshatra = VEDIC_NAKSHATRA_NAAMKARAN[safeIdx];
  const safePada = Math.max(1, Math.min(4, pada));
  const currentPada = nakshatra.padas.find((p) => p.pada === safePada) || nakshatra.padas[0];

  return {
    nakshatra,
    currentPada,
    allPadas: nakshatra.padas,
  };
}
