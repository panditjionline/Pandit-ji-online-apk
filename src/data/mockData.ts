export function getTodayPanchang(
  now: Date = new Date(),
  customDayPanchang?: CalendarDayPanchang
): PanchangData {
  const istParts = getISTDateParts(now);
  const calcDay =
    customDayPanchang ||
    buildSingleDayPanchang(istParts.year, istParts.month, istParts.day, true, now);

  const dayName = calcDay.vaarHindi;
  const formattedDate = calcDay.formattedDateHindi;
  const locShort = (calcDay.locationName || 'रुद्रपुर').split(',')[0];

  return {
    date: formattedDate,
    hinduDate: `विक्रम संवत ${calcDay.vikramSamvat}, ${calcDay.hinduMaas}, ${calcDay.paksha}, ${calcDay.tithiShort} (${dayName})`,
    tithi: `${calcDay.tithiName} (${calcDay.tithiEndTime})`,
    paksha: `${calcDay.paksha} (${calcDay.hinduMaas})`,
    nakshatra: `${calcDay.nakshatra} (${calcDay.nakshatraEndTime})`,
    yoga: `${calcDay.yoga} (${calcDay.yogaEndTime})`,
    karana: `${calcDay.karana} (${calcDay.karanaEndTime})`,
    suryaUday: calcDay.sunrise.includes('(') ? calcDay.sunrise : `${calcDay.sunrise} (${locShort})`,
    suryaAst: calcDay.sunset.includes('(') ? calcDay.sunset : `${calcDay.sunset} (${locShort})`,
    chandraUday: calcDay.moonrise,
    abhijitMuhurat: `${calcDay.abhijitMuhurat} (अति शुभ)`,
    rahuKaal: calcDay.rahuKaal.includes('(') ? calcDay.rahuKaal : `${calcDay.rahuKaal} (अशुभ)`,
    yamagandam: calcDay.yamagandam,
    gulikaKaal: calcDay.gulikaKaal,
    dishaShool: calcDay.dishaShool,
    dishaShoolRemedy: calcDay.dishaShoolRemedy,
    specialFestival: calcDay.festivalName
      ? `महापर्व/व्रत: ${calcDay.festivalName}`
      : `${formattedDate}: ${dayName} व्रत एवं विशेष पूजन`,
    choghadiya: calcDay.dayChoghadiya.map((c) => ({
      name: c.hindiName,
      type: c.type,
      time: c.time,
    })),
  };
}

